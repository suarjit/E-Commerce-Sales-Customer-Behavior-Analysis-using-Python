"""QUESTION 7: UNUSUAL TRANSACTIONS AND OUTLIERS"""

def iqr_outlier_summary(series, column_name):
    values = series.dropna()
    q1 = values.quantile(0.25)
    q3 = values.quantile(0.75)
    iqr = q3 - q1
    lower = q1 - 1.5 * iqr
    upper = q3 + 1.5 * iqr
    mask = (values < lower) | (values > upper)
    return {
        "Variable": column_name,
        "LowerBound": lower,
        "UpperBound": upper,
        "OutlierCount": int(mask.sum())
    }

outlier_summary = pd.DataFrame([
    iqr_outlier_summary(sales["Quantity"], "Quantity"),
    iqr_outlier_summary(sales["UnitPrice"], "UnitPrice"),
    iqr_outlier_summary(sales["Revenue"], "Line Revenue"),
    iqr_outlier_summary(order_totals["OrderValue"], "Order Value")
])

print("IQR outlier summary:")
